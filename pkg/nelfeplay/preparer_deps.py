"""Prepare le prefixe de compilation de RetroArch NelfePlay (24/11/2026, dev-natif).

Usage : python -I preparer_deps.py <dossier deps> <dossier des DLL de RetroBat>

- en-tetes : FFmpeg 4.2.3 (version des avcodec-58 & co de RetroBat), freetype 2.10.4, SDL2 2.0.14 (paquet devel mingw) ;
- bibliotheques d'import tirees des DLL DE LA BORNE (export table -> .def -> dlltool) : l'editeur de liens refuse
  alors toute fonction absente de la DLL que l'exe trouvera chez le joueur ;
- fichiers .pc dans <deps>/prefix/lib/pkgconfig (PKG_CONFIG_LIBDIR exclusif : configure ne voit rien de MSYS2).
"""
import os
import re
import shutil
import subprocess
import sys

BIN = r"E:\msys64\mingw64\bin"
OBJDUMP = os.path.join(BIN, "objdump.exe")
DLLTOOL = os.path.join(BIN, "dlltool.exe")

DLLS = {  # nom pkg-config : (dll de la borne, nom de lib, version annoncee, en-tetes)
    "libavcodec": ("avcodec-58.dll", "avcodec", "58.54.100"),
    "libavformat": ("avformat-58.dll", "avformat", "58.29.100"),
    "libavdevice": ("avdevice-58.dll", "avdevice", "58.8.100"),
    "libavutil": ("avutil-56.dll", "avutil", "56.31.100"),
    "libswresample": ("swresample-3.dll", "swresample", "3.5.100"),
    "libswscale": ("swscale-5.dll", "swscale", "5.5.100"),
    "freetype2": ("libfreetype-6.dll", "freetype", "23.4.17"),
}


def exports(dll):
    texte = subprocess.run([OBJDUMP, "-p", dll], capture_output=True, text=True, errors="replace").stdout
    noms, dedans = [], False
    for ligne in texte.splitlines():
        if ligne.startswith("[Ordinal/Name Pointer] Table") or ligne.startswith("[Name Pointer/Ordinal] Table"):
            dedans = True
            continue
        if dedans:
            m = re.match(r"\s*\[\s*\d+\]\s+(?:\+base\[\s*\d+\]\s+[0-9a-fA-F]+\s+)?(\S+)", ligne)
            if m:
                noms.append(m.group(1))
            elif ligne.strip() == "":
                if noms:
                    break
    return noms


def main():
    deps, borne = sys.argv[1], sys.argv[2]
    src = os.path.join(deps, "src")
    prefix = os.path.join(deps, "prefix")
    inc, lib = os.path.join(prefix, "include"), os.path.join(prefix, "lib")
    pc = os.path.join(lib, "pkgconfig")
    for d in (inc, lib, pc):
        os.makedirs(d, exist_ok=True)

    ff = os.path.join(src, "ffmpeg-4.2.3")
    for sous in ("libavcodec", "libavformat", "libavdevice", "libavutil", "libswresample", "libswscale"):
        dst = os.path.join(inc, sous)
        os.makedirs(dst, exist_ok=True)
        for f in os.listdir(os.path.join(ff, sous)):
            if f.endswith(".h"):
                shutil.copy2(os.path.join(ff, sous, f), dst)
    with open(os.path.join(inc, "libavutil", "avconfig.h"), "w") as f:
        f.write("/* Generated by ffmpeg configure */\n#ifndef AVUTIL_AVCONFIG_H\n#define AVUTIL_AVCONFIG_H\n"
                "#define AV_HAVE_BIGENDIAN 0\n#define AV_HAVE_FAST_UNALIGNED 1\n#endif /* AVUTIL_AVCONFIG_H */\n")
    with open(os.path.join(inc, "libavutil", "ffversion.h"), "w") as f:
        f.write("#ifndef AVUTIL_FFVERSION_H\n#define AVUTIL_FFVERSION_H\n#define FFMPEG_VERSION \"4.2.3\"\n#endif\n")

    ft = os.path.join(src, "freetype-2.10.4", "include")
    shutil.copytree(ft, os.path.join(inc, "freetype2"), dirs_exist_ok=True)

    sdl = os.path.join(src, "SDL2-2.0.14", "x86_64-w64-mingw32")
    shutil.copytree(os.path.join(sdl, "include", "SDL2"), os.path.join(inc, "SDL2"), dirs_exist_ok=True)
    shutil.copy2(os.path.join(sdl, "lib", "libSDL2main.a"), lib)

    for nom, (dll, court, version) in list(DLLS.items()) + [("sdl2", ("SDL2.dll", "SDL2", "2.0.14"))]:
        chemin = os.path.join(borne, dll)
        noms = exports(chemin)
        if not noms:
            raise SystemExit(f"aucun export lu dans {chemin}")
        deff = os.path.join(lib, court + ".def")
        with open(deff, "w") as f:
            f.write(f"LIBRARY \"{dll}\"\nEXPORTS\n")
            for n in noms:
                f.write(f"    {n}\n")
        subprocess.run([DLLTOOL, "-d", deff, "-D", dll, "-l", os.path.join(lib, f"lib{court}.dll.a")], check=True)
        if nom == "sdl2":
            libs = "-L${libdir} -lmingw32 -lSDL2main -lSDL2 -mwindows"
            cflags = "-I${includedir}/SDL2 -Dmain=SDL_main"
        elif nom == "freetype2":
            libs, cflags = "-L${libdir} -lfreetype", "-I${includedir}/freetype2"
        else:
            libs, cflags = f"-L${{libdir}} -l{court}", "-I${includedir}"
        with open(os.path.join(pc, nom + ".pc"), "w") as f:
            f.write(f"prefix={prefix.replace(os.sep, '/')}\nlibdir=${{prefix}}/lib\nincludedir=${{prefix}}/include\n\n"
                    f"Name: {nom}\nDescription: import de {dll} (RetroBat)\nVersion: {version}\n"
                    f"Libs: {libs}\nCflags: {cflags}\n")
        print(f"{nom:14} {dll:20} {len(noms):5} exports")


if __name__ == "__main__":
    main()
